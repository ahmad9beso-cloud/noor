// Release signing comes from environment variables (see README / CI workflow).
// Without them the release build is signed with the local debug key so it still installs.
val keystorePath: String? = System.getenv("KEYSTORE_PATH")

android {
    namespace = "app.noor.islamic"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.noor.islamic"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0.0"

        // arm64 only: smaller APK. Add "armeabi-v7a" / "x86_64" here if you ever need them.
        ndk { abiFilters += "arm64-v8a" }

        // The UI is Arabic only; drop every other locale's library strings.
        resourceConfigurations += "ar"
    }

    signingConfigs {
        if (keystorePath != null && file(keystorePath).exists()) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
            excludes += "/META-INF/*.version"
            excludes += "/kotlin/**"
            excludes += "/DebugProbesKt.bin"
        }
    }
}

